I('{geodesicCheck[{{1, 0}, {0, Sin[\\[Theta]]^2}}, {\\[Theta], \\[Phi]}, {p\\[Theta], p\\[Phi]}], geodesicCheck[{{1/y^2, 0}, {0, 1/y^2}}, {x, y}, {px, py}]}')
