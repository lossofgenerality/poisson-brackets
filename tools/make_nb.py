I('With[{Hp = pp^2/2 - Cos[qq]},\n Show[StreamPlot[Evaluate[{D[Hp, pp], -D[Hp, qq]}], {qq, -2 Pi, 2 Pi}, {pp, -3, 3}],\n  ContourPlot[Hp, {qq, -2 Pi, 2 Pi}, {pp, -3, 3}, ContourShading -> None, Contours -> 12],\n  FrameLabel -> {"q", "p"}, PlotLabel -> "Pendulum: flow of X_H along level sets of H"]]')

S("2. Intuition: area, rate, and the quantum shadow")
I('pb1[f[q, p], g[q, p]] == Det[D[{f[q, p], g[q, p]}, {{q, p}}]] // Simplify')
